#include <stdio.h>

int ft_atoi(const char *s) 
{ 
	int	sign = 1, n = 0; 
	
	while (*s == ' ' || *s == '\t' || *s == '\n') 
		s++; 
	if (*s == '-')
	{	
		sign = -1;
		s++; 
	}
	else if (*s == '+') 
		s++; 
	while (*s >= '0' && *s <= '9') 
	{
		//n = n * 10 + (*s++ - '0'); 
		n = n * 10 + (*s - '0');
		*s++;
	}	
	return sign * n; 
}
